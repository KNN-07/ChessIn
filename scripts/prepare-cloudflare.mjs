import { createHash } from 'node:crypto';
import { createReadStream, createWriteStream } from 'node:fs';
import { copyFile, mkdir, readdir, rename, rm, stat, writeFile } from 'node:fs/promises';
import { Transform } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const dist = path.join(root, 'apps/web/dist');
const staging = path.join(root, '.cloudflare/assets');
const temporary = path.join(root, '.cloudflare/assets-next');
const manifest = path.join(root, '.cloudflare/asset-manifest.mjs');
// Deliberately below the 25 MiB Workers Static Assets per-file limit.
const partBytes = 20 * 1024 * 1024;
const internalPrefix = '__chessin_parts';
const largeAssets = Object.create(null);

function mime(name) {
  if (name.endsWith('.wasm')) return 'application/wasm';
  if (name.endsWith('.js')) return 'text/javascript; charset=utf-8';
  if (name.endsWith('.nnue')) return 'application/octet-stream';
  if (name.endsWith('.tar.gz')) return 'application/gzip';
  return 'application/octet-stream';
}

async function stageDirectory(relative = '') {
  const source = path.join(dist, relative);
  for (const entry of await readdir(source, { withFileTypes: true })) {
    if (!relative && entry.name === internalPrefix) throw Error(`Reserved Workers asset path: ${entry.name}`);
    const child = path.join(relative, entry.name);
    if (entry.isDirectory()) {
      await mkdir(path.join(temporary, child), { recursive: true });
      await stageDirectory(child);
    } else if (entry.isFile()) {
      const original = path.join(dist, child);
      const size = (await stat(original)).size;
      if (size <= partBytes) {
        await copyFile(original, path.join(temporary, child));
        continue;
      }
      const url = '/' + child.split(path.sep).join('/');
      const id = createHash('sha256').update(url).digest('hex');
      const partDirectory = path.join(temporary, internalPrefix, id);
      await mkdir(partDirectory, { recursive: true });
      const digest = createHash('sha256');
      const parts = [];
      for (let offset = 0; offset < size; offset += partBytes) {
        const length = Math.min(partBytes, size - offset);
        const name = `part-${String(parts.length).padStart(4, '0')}`;
        const partPath = `/${internalPrefix}/${id}/${name}`;
        await pipeline(
          createReadStream(original, { start: offset, end: offset + length - 1 }),
          new Transform({ transform(chunk, encoding, callback) { digest.update(chunk); callback(null, chunk); } }),
          createWriteStream(path.join(partDirectory, name)),
        );
        if ((await stat(path.join(partDirectory, name))).size !== length) throw Error(`Incomplete part: ${partPath}`);
        parts.push({ path: partPath, size: length });
      }
      largeAssets[url] = { size, mime: mime(child), sha256: digest.digest('hex'), parts };
    } else {
      throw Error(`Cannot deploy non-file asset: ${child}`);
    }
  }
}

await stat(path.join(dist, 'index.html')); // Never deploy an empty or stale directory by accident.
await mkdir(path.dirname(staging), { recursive: true });
await rm(temporary, { recursive: true, force: true });
try {
  await mkdir(temporary);
  await stageDirectory();
  await rm(staging, { recursive: true, force: true });
  await rename(temporary, staging);
  await writeFile(`${manifest}.next`, `// Generated by scripts/prepare-cloudflare.mjs; never hand-edit.\nexport default ${JSON.stringify(largeAssets, null, 2)};\n`);
  await rename(`${manifest}.next`, manifest);
  console.log(`Staged Workers assets: ${Object.keys(largeAssets).length} split files, ${Object.values(largeAssets).reduce((n, item) => n + item.parts.length, 0)} parts.`);
} catch (error) {
  await rm(temporary, { recursive: true, force: true });
  await rm(`${manifest}.next`, { force: true });
  throw error;
}
